class MainActivity : ComponentActivity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        enableEdgeToEdge()
        val launchId = intent?.getIntExtra(AppWidgetManager.EXTRA_APPWIDGET_ID, AppWidgetManager.INVALID_APPWIDGET_ID)
            ?: AppWidgetManager.INVALID_APPWIDGET_ID
        if (launchId != AppWidgetManager.INVALID_APPWIDGET_ID) {
            // Accept straight away so backing out never removes the widget.
            setResult(RESULT_OK, Intent().putExtra(AppWidgetManager.EXTRA_APPWIDGET_ID, launchId))
            Widgets.refresh(this, intArrayOf(launchId))
            Refresher.schedule(this)
        }
        setContent { HiatusTheme { Root(launchId) } }
    }
}

private enum class Tab(val label: String) { TODAY("Today"), WIDGETS("Widgets") }

@Composable
private fun Root(launchId: Int) {
    val ctx = LocalContext.current
    val scope = rememberCoroutineScope()
    var granted by remember { mutableStateOf(Usage.hasAccess(ctx)) }
    var report by remember { mutableStateOf<Report?>(null) }
    var refreshing by remember { mutableStateOf(false) }

    fun load(pulled: Boolean) {
        scope.launch {
            if (pulled) refreshing = true
            report = withContext(Dispatchers.Default) { runCatching { Usage.report(ctx) }.getOrNull() }
            refreshing = false
            report?.let { Widgets.remember(it) }
            Widgets.refresh(ctx, fresh = report == null)
        }
    }

    LifecycleResumeEffect(Unit) {
        granted = Usage.hasAccess(ctx)
        if (granted) load(false) else { report = null; Widgets.refresh(ctx) }
        onPauseOrDispose { }
    }
    // Leaving the app: make sure every widget shows the latest settings before Android freezes the process.
    LifecycleEventEffect(Lifecycle.Event.ON_STOP) { Widgets.refresh(ctx, fresh = false) }

    var tab by rememberSaveable { mutableStateOf(if (launchId >= 0) Tab.WIDGETS else Tab.TODAY) }
    var settings by rememberSaveable { mutableStateOf(false) }
    BackHandler(enabled = settings) { settings = false }

    if (launchId >= 0) {
        // Opened by the launcher while adding a widget: just the editor, with Done.
        val activity = ctx as? android.app.Activity
        WidgetEditor(launchId, report, onDone = { activity?.finish() })
        return
    }

    AnimatedContent(
        targetState = settings,
        transitionSpec = {
            val dir = if (targetState) 1 else -1
            (slideInHorizontally(tween(320, easing = FastOutSlowInEasing)) { w -> dir * w / 6 } + fadeIn(tween(220, delayMillis = 60)))
                .togetherWith(slideOutHorizontally(tween(320, easing = FastOutSlowInEasing)) { w -> -dir * w / 6 } + fadeOut(tween(120)))
        },
        label = "settings",
    ) { inSettings ->
        if (inSettings) {
            AppSettingsScreen(granted, onBack = { settings = false }, onTrackingChanged = { if (granted) load(false) })
        } else {
            Scaffold(
                contentWindowInsets = WindowInsets(0, 0, 0, 0),
                bottomBar = {
                    NavigationBar {
                        Tab.entries.forEach { t ->
                            val selected = tab == t
                            NavigationBarItem(
                                selected = selected,
                                onClick = { tab = t },
                                icon = {
                                    Icon(
                                        when (t) {
                                            Tab.TODAY -> if (selected) Icons.Rounded.Insights else Icons.Outlined.Insights
                                            Tab.WIDGETS -> if (selected) Icons.Rounded.Widgets else Icons.Outlined.Widgets
                                        },
                                        contentDescription = null,
                                    )
                                },
                                label = { Text(t.label) },
                            )
                        }
                    }
                },
            ) { pad ->
                Box(Modifier.fillMaxSize().padding(bottom = pad.calculateBottomPadding())) {
                    Crossfade(targetState = tab, animationSpec = tween(220), label = "tab") { shown ->
                        when (shown) {
                            Tab.TODAY -> TodayScreen(report, granted, refreshing, onRefresh = { load(true) }, onOpenSettings = { settings = true })
                            Tab.WIDGETS -> WidgetEditor(launchId, report)
                        }
                    }
                }
            }
        }
    }
}
